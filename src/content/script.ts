/**
 * Голос воронки. Дословно по текстовому прототипу заказчика.
 *
 * Город идёт сам 60–90 секунд: человек ничего не нажимает каждые пять секунд.
 * Реплики разбиты на субтитры так, как их будет читать голос — по смыслу,
 * а не по длине строки. `hold` — сколько кадр держит реплику, в миллисекундах,
 * когда озвучки ещё нет; с озвучкой тайминг берётся из аудиодорожки.
 */

export interface Line {
  text: string
  hold: number
  /** Реплика-поворот: кадр в этот момент меняет план. */
  beat?: boolean
}

