/**
 * ДАЛЬШЕ ВСЁ ЧИТАЕТСЯ ТЕКСТОМ.
 *
 * Голосовое остаётся ровно одно — открытие города: там человек только пришёл,
 * ему нужно дать осмотреться, и голос поверх кадра работает как кино. Каждый
 * следующий голосовой превращает мост в ожидание: текста немного, человек
 * прочитает его быстрее, чем прослушает, и сам решит, когда идти дальше.
 *
 * `lead` — сказанное в полный голос, `note` — пояснение тише,
 * `quote` — реплика, которой человек обычно отмахивается, произнесённая за него.
 */
export type BridgeBlock = { kind: 'lead' | 'note' | 'quote'; text: string }

