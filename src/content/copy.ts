export interface Line {
  /** Субтитр: то, что произносит голос. */
  text: string
  /** Сколько кадр держит реплику без озвучки, мс. С аудио тайминг берётся из файла. */
  hold: number
  /** Реплика-поворот: кадр в этот момент меняет план. */
  beat?: boolean
  /**
   * Ключевая фраза, которая в этот момент становится частью города (§5):
   * крупная типографика поверх кадра, а не строка субтитра.
   */
  accent?: string
  /** Район города, через который летим на этой реплике (§5). */
  district?: 'direct' | 'vk' | 'avito' | 'tgads' | 'conversions' | 'lab'
}

