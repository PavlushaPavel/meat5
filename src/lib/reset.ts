/**
 * `?reset=1` — начать маршрут заново.
 *
 * Нужно для приёмки. Прогресс переживает закрытие приложения (так и задумано),
 * но человеку, который смотрит воронку в десятый раз, восстановление честно
 * открывает девятое состояние — и всё, что до него, он не видит вообще.
 * Один параметр в адресе возвращает его в самое начало.
 *
 * Модуль работает СРАЗУ при загрузке и обязан отработать ДО того, как zustand
 * поднимет сохранённое состояние. Поэтому он импортируется в main.tsx первой
 * строкой: модули вычисляются в порядке импортов, и стор к этому моменту ещё
 * не тронут. Переставить импорт ниже — значит сломать сброс.
 */
const PROGRESS_KEY = 'traffic-city-progress'
const ATTRIBUTION_KEY = 'traffic-lab-attribution'

try {
  const params = new URLSearchParams(window.location.search)
  if (params.get('reset') === '1') {
    localStorage.removeItem(PROGRESS_KEY)
    // Атрибуцию не трогаем: first_touch по смыслу пишется один раз за человека,
    // и сброс прохождения не должен подменять источник, из которого он пришёл.
    void ATTRIBUTION_KEY
    // Убираем параметр из адреса, чтобы обновление страницы не сбрасывало
    // прогресс снова и снова — иначе воронку невозможно пройти дальше первого шага.
    params.delete('reset')
    const query = params.toString()
    window.history.replaceState(
      null,
      '',
      window.location.pathname + (query ? `?${query}` : '') + window.location.hash,
    )
  }
} catch {
  /* приватный режим: сбрасывать нечего, молча идём дальше */
}

export {}
